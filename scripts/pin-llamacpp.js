#!/usr/bin/env bun
/**
 * Regenerate src/local/llamacpp-pins.js from a llama.cpp GitHub release.
 *
 *   bun run scripts/pin-llamacpp.js            # the newest release with binaries
 *   bun run scripts/pin-llamacpp.js b11320     # a named build
 *
 * The CLI downloads llama-server only at the build pinned here, and refuses a
 * file whose sha256 differs from the one recorded below. The digest comes from
 * the GitHub release API's `digest` field. Run the tests after: they check
 * every pinned key still resolves to a file.
 *
 * Dev-only. Not part of the bundle (the build entry is src/cli/index.js).
 */

import fs from "node:fs";
import path from "node:path";

const REPO = "ggml-org/llama.cpp";
const OUT = path.join(import.meta.dirname, "..", "src", "local", "llamacpp-pins.js");

/**
 * The builds aile offers, by platform key. `extra` is a second archive
 * extracted beside the first (the CUDA runtime). `minDriver` is the NVIDIA
 * driver the CUDA build needs; below it the next choice is Vulkan.
 */
const WANT = {
  "win-x64-cpu": { file: (t) => `llama-${t}-bin-win-cpu-x64.zip` },
  "win-x64-vulkan": { file: (t) => `llama-${t}-bin-win-vulkan-x64.zip` },
  "win-x64-cuda": { file: (t) => `llama-${t}-bin-win-cuda-12.4-x64.zip`, extra: () => "cudart-llama-bin-win-cuda-12.4-x64.zip", minDriver: "551.61" },
  "win-arm64-cpu": { file: (t) => `llama-${t}-bin-win-cpu-arm64.zip` },
  "macos-arm64": { file: (t) => `llama-${t}-bin-macos-arm64.tar.gz` },
  "macos-x64": { file: (t) => `llama-${t}-bin-macos-x64.tar.gz` },
  "linux-x64-cpu": { file: (t) => `llama-${t}-bin-ubuntu-x64.tar.gz` },
  "linux-x64-vulkan": { file: (t) => `llama-${t}-bin-ubuntu-vulkan-x64.tar.gz` },
  "linux-x64-cuda": { file: (t) => `llama-${t}-bin-ubuntu-cuda-12.8-x64.tar.gz`, extra: (t) => `cudart-llama-${t}-bin-ubuntu-cuda-12.8-x64.tar.gz`, minDriver: "570.26" },
  "linux-arm64-cpu": { file: (t) => `llama-${t}-bin-ubuntu-arm64.tar.gz` },
};

async function gh(pathname) {
  const res = await fetch(`https://api.github.com/repos/${REPO}${pathname}`, {
    headers: { accept: "application/vnd.github+json", ...(process.env.GITHUB_TOKEN ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}) },
  });
  if (!res.ok) throw new Error(`GitHub answered HTTP ${res.status} for ${pathname}`);
  return res.json();
}

const wanted = process.argv[2];
const release = wanted
  ? await gh(`/releases/tags/${wanted}`)
  : (await gh("/releases?per_page=20")).find((r) => /^b\d+$/.test(r.tag_name) && r.assets?.length > 10);
if (!release) throw new Error("no release with binaries found");
const tag = release.tag_name;
const byName = new Map(release.assets.map((a) => [a.name, a]));

const pick = (name) => {
  const a = byName.get(name);
  if (!a) throw new Error(`${tag} has no asset ${name}`);
  if (!/^sha256:[0-9a-f]{64}$/.test(a.digest || "")) throw new Error(`${name} carries no sha256 digest`);
  return { file: name, size: a.size, sha256: a.digest.slice(7) };
};

const assets = {};
for (const [key, w] of Object.entries(WANT)) {
  assets[key] = { ...pick(w.file(tag)), ...(w.extra ? { extra: pick(w.extra(tag)) } : {}), ...(w.minDriver ? { minDriver: w.minDriver } : {}) };
}

const body = `/**
 * GENERATED by scripts/pin-llamacpp.js — do not edit by hand.
 *
 * The llama.cpp build \`aile local\` installs, with each archive's sha256 as
 * GitHub publishes it. A download that does not match is deleted and refused.
 * Release: https://github.com/${REPO}/releases/tag/${tag} (${release.published_at?.slice(0, 10)})
 */

export const LLAMACPP_PINS = ${JSON.stringify({ tag, assets }, null, 2)};
`;
fs.writeFileSync(OUT, body);
console.log(`pinned ${tag}: ${Object.keys(assets).length} builds → ${path.relative(process.cwd(), OUT)}`);
